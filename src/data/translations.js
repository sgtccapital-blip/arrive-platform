/**
 * Safe translation getter with fallback
 */
export const t = (path, locale = 'es') => {
  const parts = path.split('.');
  let current = TRANSLATIONS;
  for (const p of parts) {
    if (current && current[p] !== undefined) {
      current = current[p];
    } else {
      return path;
    }
  }
  if (typeof current === 'object' && current !== null) {
    return current[locale] || current.es || current.en || path;
  }
  return current || path;
};
